import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptPath = fileURLToPath(import.meta.url)
const projectRoot = resolve(dirname(scriptPath), '..')
const outputDir = join(projectRoot, 'dist')

async function collectAssets(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const assets = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) return collectAssets(path)
    const asset = relative(outputDir, path).split(sep).join('/')
    // Never cache this worker, source maps, or GitHub Pages control files.
    return entry.isFile() && asset !== 'sw.js' && !asset.endsWith('.map')
      && !asset.split('/').some((part) => part.startsWith('.')) && asset !== 'CNAME'
      ? [asset] : []
  }))
  return assets.flat().sort()
}

const assets = await collectAssets(outputDir)
if (!assets.includes('index.html') || !assets.includes('manifest.webmanifest')) {
  throw new Error('Build the Vite app, including its web manifest, before generating the service worker.')
}

// Include the generator so a change to the caching strategy also creates a new version.
const hash = createHash('sha256').update(await readFile(scriptPath))
for (const asset of assets) {
  hash.update(asset).update('\0').update(await readFile(join(outputDir, asset))).update('\0')
}
const version = hash.digest('hex').slice(0, 20)

const worker = `/* MooSPA production service worker. Generated by scripts/build-pwa.mjs. */
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(assets)};
// GitHub Pages repositories share an origin. Limit cleanup to this app AND scope.
const CACHE_PREFIX = 'moospa-precache:' + self.registration.scope + ':';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const ASSET_URLS = ASSETS.map((asset) => new URL(asset, self.registration.scope).href);
const ASSET_SET = new Set(ASSET_URLS);
const SHELL_URL = new URL('index.html', self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(ASSET_URLS.map((url) => new Request(url, { cache: 'reload' })));
    // An update waits until the user chooses to apply it, or all old tabs close.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    event.waitUntil(self.skipWaiting());
  }
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;

  // Only the app shell and build-time static assets enter this cache.
  // Session state and mock interactions are never persisted by the worker.
  url.search = '';
  url.hash = '';
  const isNavigation = request.mode === 'navigate';
  if (!isNavigation && !ASSET_SET.has(url.href)) return;
  const cacheKey = isNavigation ? SHELL_URL : url.href;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(cacheKey);
    if (cached) return cached;
    // Do not create runtime caches: a missing asset is fetched normally.
    return fetch(request);
  })());
});
`

await writeFile(join(outputDir, 'sw.js'), worker)
console.log(`PWA: ${assets.length} static assets, cache version ${version}`)
